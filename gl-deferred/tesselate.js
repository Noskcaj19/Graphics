function drawLine(from, to) {
    ctx.beginPath(); // Start a new path
    ctx.moveTo(...from); // Move the pen to (30, 50)
    ctx.lineTo(...to); // Draw a line to (150, 100)
    ctx.closePath()
    ctx.stroke(); // Render the path
}


